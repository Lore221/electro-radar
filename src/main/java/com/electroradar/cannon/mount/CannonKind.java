package com.electroradar.cannon.mount;

/** Тип орудия на установке CBC, определяющий чтение снаряда и способ выстрела. */
public enum CannonKind {
    /** Большая пушка: один выстрел на фронт сигнала, заряд складывается из пороха в стволе. */
    BIG_CANNON,
    /** Автопушка: стреляет, пока есть сигнал; время жизни снаряда ограничено материалом. */
    AUTOCANNON
}
