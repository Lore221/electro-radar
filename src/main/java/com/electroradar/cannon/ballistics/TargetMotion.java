package com.electroradar.cannon.ballistics;

/**
 * Движение цели в тиках полёта снаряда, относительно центра пушки на момент запуска.
 *
 * <p>Решателю нужны две вещи: положение цели во время отрезка столкновений тика {@code n} и
 * граница её смещения за тик, на которой держится безопасный пропуск тиков
 * ({@link InterceptSearch}). Закон движения может быть любым: равноускоренная цель
 * ({@link TargetForecast}) или баллистический снаряд с сопротивлением.</p>
 */
public interface TargetMotion {
    /** Положение цели во время отрезка столкновений тика {@code tick}. */
    Vector3 positionAt(int tick);

    /**
     * Верхняя граница {@code |X(n + 1) − X(n)|} для всех {@code n < tick}: на ней основан пропуск
     * тиков, поэтому занижать её нельзя.
     */
    double speedBound(int tick);
}
