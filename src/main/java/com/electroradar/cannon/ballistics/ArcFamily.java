package com.electroradar.cannon.ballistics;

/**
 * Семейство траектории, к которому относится попадание.
 *
 * <p>Определяется по самому отрезку столкновений, а не по непрерывной траектории: при
 * фиксированной цели производная её рассогласования по высоте по {@code tan(pitch)} внутри отрезка
 * пропорциональна {@code 1 − (w/U)·u_y}, и {@code ∂F/∂f = −2·ρ·U·(1 − (w/U)·u_y)}. Поэтому
 * {@link #LOW} — корень, в котором {@code F(f)} убывает (подъём ствола поднимает траекторию над
 * целью), {@link #HIGH} — корень, в котором растёт. В одном тике каждого семейства не больше одного
 * корня.</p>
 */
public enum ArcFamily {
    /** Настильная ветвь: увеличение угла места поднимает траекторию в точке цели. */
    LOW,
    /** Навесная ветвь: увеличение угла места опускает траекторию в точке цели. */
    HIGH
}
