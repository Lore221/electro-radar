package com.electroradar.radar.network;

/**
 * Типизированное преобразование цели сети в запись, нужную конкретному потребителю.
 *
 * <p>Ядро само определяет полный набор целей, доступных регистрации, и вызывает проекцию
 * ровно один раз для каждой уникальной цели. Проекция получает только неизменяемое read-only
 * представление: внутренние карты сети ей недоступны. Она должна быть чистой и не должна
 * сохранять {@link TargetView}: представление действительно только во время вызова метода.
 * Возвращаемую запись обычно следует делать неизменяемым record. Подробные {@link RadarSource}
 * строятся только если проекция действительно вызвала {@link TargetView#sources()}.</p>
 *
 * @param <T> тип одной записи результата, выбранный потребителем
 */
@FunctionalInterface
public interface TargetProjection<T> {
    /**
     * Создаёт одну запись ответа из опубликованных данных цели.
     *
     * @param target read-only данные одной цели; их нельзя сохранять для отложенного чтения
     * @return запись потребителя; {@code null} не допускается
     */
    T project(TargetView target);
}
